/// Selecting an audio track by id is what the audio menu will do.
#[test]
fn an_audio_track_can_be_selected() {
    if !mpv_available() {
        return;
    }
    let Some(media) = test_media() else {
        return;
    };

    let mut mpv = Mpv::start(&media, &options()).expect("mpv sollte starten");
    std::thread::sleep(Duration::from_secs(2));

    let list = mpv.track_list();
    let audio = list.audio();
    if audio.len() < 2 {
        eprintln!("übersprungen: die Testdatei hat weniger als zwei Audiospuren");
        return;
    }
    let target = audio
        .iter()
        .find(|t| !t.selected)
        .expect("eine nicht gewählte Spur");
    let target_id = target.id;

    mpv.send(&serde_json::json!(["set_property", "aid", target_id]))
        .expect("Audiospur sollte wählbar sein");
    std::thread::sleep(Duration::from_secs(1));

    assert_eq!(
        mpv.property("aid").as_i64(),
        Some(target_id),
        "die gewählte Audiospur wurde nicht übernommen"
    );
}

