//! Integration tests for the mpv process and IPC layer.
//!
//! The unit tests in `src/mpv.rs` cover every decision — argument building, track
//! parsing, language matching, the state machine. What they cannot cover is the part
//! that only exists against a real process: that mpv starts, accepts the argument
//! list, creates its socket, answers `get_property`, and survives the observer
//! registration order that spike 0.3 found to matter.
//!
//! These tests **skip** when `mpv` is not installed or the test media is missing, so
//! the crate still builds and tests in a bare container. They are run for real in this
//! repository's development container, which is the point: the six silent IPC defects
//! from spike 0.3 were all invisible to unit tests.

use std::process::Command;
use std::time::Duration;

use streamarr_desktop_player::mpv::{HdrMode, Mpv, PlayerOptions, PlayerState, TrackKind};

/// Whether a real mpv is available.
fn mpv_available() -> bool {
    Command::new("mpv")
        .arg("--version")
        .output()
        .map(|out| out.status.success())
        .unwrap_or(false)
}

/// Test media, generated by the spike script rather than committed.
///
/// Checked at several plausible locations because the host and the development
/// container see different `/tmp` directories.
fn test_media() -> Option<String> {
    for candidate in ["/tmp/mpvt/test.mkv", "/var/tmp/mpvt/test.mkv"] {
        if std::path::Path::new(candidate).exists() {
            return Some(candidate.to_string());
        }
    }
    None
}

/// Media with a separate subtitle file next to it.
fn media_with_subtitles() -> Option<String> {
    for candidate in ["/tmp/mpvt/sub.mkv", "/var/tmp/mpvt/sub.mkv"] {
        if std::path::Path::new(candidate).exists() {
            return Some(candidate.to_string());
        }
    }
    None
}

fn options() -> PlayerOptions {
    PlayerOptions {
        // No window: these tests must run without a display server. `--vo=null`
        // decodes and discards, which is exactly what is being verified.
        vo: "null".to_string(),
        fullscreen: false,
        ..Default::default()
    }
}

/// mpv must start, create its socket, and load the file.
#[test]
fn mpv_starts_and_loads_a_file() {
    if !mpv_available() {
        eprintln!("übersprungen: mpv ist nicht installiert");
        return;
    }
    let Some(media) = test_media() else {
        eprintln!("übersprungen: Testmedium /tmp/mpvt/test.mkv fehlt");
        return;
    };

    let mut mpv = Mpv::start(&media, &options()).expect("mpv sollte starten");

    // A duration is only known once the file is open, which makes it the reliable
    // signal that loading worked.
    let deadline = std::time::Instant::now() + Duration::from_secs(15);
    let mut duration = 0.0;
    while std::time::Instant::now() < deadline {
        duration = mpv.property("duration").as_f64().unwrap_or(0.0);
        if duration > 0.0 {
            break;
        }
        std::thread::sleep(Duration::from_millis(200));
    }
    assert!(
        duration > 0.0,
        "mpv meldete keine Dauer — Datei nicht geladen"
    );
}

/// The observer registration order from spike 0.3 (defect 5): registered before
/// `loadfile`, `time-pos` events never arrived. This asserts the order in `start`
/// actually produces them.
#[test]
fn property_events_actually_arrive() {
    if !mpv_available() {
        return;
    }
    let Some(media) = test_media() else {
        return;
    };

    let mut mpv = Mpv::start(&media, &options()).expect("mpv sollte starten");
    let mut state = PlayerState::default();

    // `time-pos` arrives roughly per frame; ten seconds is ample and keeps a broken
    // build from hanging the suite.
    let deadline = std::time::Instant::now() + Duration::from_secs(20);
    while std::time::Instant::now() < deadline {
        if let Some(event) = mpv.next_event(Duration::from_millis(500)) {
            if event.get("event").and_then(|v| v.as_str()) == Some("property-change") {
                let name = event
                    .get("name")
                    .and_then(|v| v.as_str())
                    .unwrap_or_default();
                let data = event
                    .get("data")
                    .cloned()
                    .unwrap_or(serde_json::Value::Null);
                state.apply_event(name, &data);
            }
        }
        if state.position > 0.0 {
            break;
        }
    }
    assert!(
        state.position > 0.0,
        "keine time-pos-Ereignisse empfangen — die Beobachter-Reihenfolge ist falsch"
    );
}

/// `track-list` is large enough to arrive fragmented, which is defect 4. Parsing a
/// fragment yields an empty list that looks like a file with no tracks.
#[test]
fn the_track_list_is_received_completely() {
    if !mpv_available() {
        return;
    }
    let Some(media) = test_media() else {
        return;
    };

    let mut mpv = Mpv::start(&media, &options()).expect("mpv sollte starten");

    // Wait for playback to start; the track list is only complete once demuxing began.
    std::thread::sleep(Duration::from_secs(2));

    let list = mpv.track_list();
    assert!(
        !list.tracks.is_empty(),
        "die Spurenliste kam leer an — vermutlich ein zerschnittenes IPC-Reply"
    );
    assert!(
        !list.of_kind(TrackKind::Video).is_empty(),
        "keine Videospur gefunden: {:?}",
        list.tracks
    );
    assert!(
        !list.audio().is_empty(),
        "keine Audiospur gefunden: {:?}",
        list.tracks
    );
}

/// mpv rejects a numeric argument sent as a string ("invalid parameter") and then
/// emits nothing at all — defect 1. This proves the typed path works.
#[test]
fn commands_and_replies_are_matched_by_request_id() {
    if !mpv_available() {
        return;
    }
    let Some(media) = test_media() else {
        return;
    };

    let mut mpv = Mpv::start(&media, &options()).expect("mpv sollte starten");
    std::thread::sleep(Duration::from_secs(2));

    // Two requests in a row: if replies were not matched by id, one of these would
    // receive the other's answer.
    let volume = mpv.property("volume");
    let muted = mpv.property("mute");
    assert!(
        volume.is_number(),
        "volume kam nicht als Zahl zurück: {volume}"
    );
    assert!(
        muted.is_boolean(),
        "mute kam nicht als Wahrheitswert zurück: {muted}"
    );

    // A number sent as a number is accepted; the reply must be an error-free record.
    let reply = mpv
        .request(serde_json::json!(["get_property", "speed"]))
        .expect("Antwort erwartet");
    assert_eq!(reply.get("error").and_then(|v| v.as_str()), Some("success"));
}

/// Pausing and resuming works over IPC, which is what the toolbar will use.
#[test]
fn playback_can_be_paused_and_resumed() {
    if !mpv_available() {
        return;
    }
    let Some(media) = test_media() else {
        return;
    };

    let mut mpv = Mpv::start(&media, &options()).expect("mpv sollte starten");
    std::thread::sleep(Duration::from_secs(2));

    mpv.send(&serde_json::json!(["set_property", "pause", true]))
        .expect("Pause sollte gesetzt werden können");
    std::thread::sleep(Duration::from_millis(500));
    assert_eq!(
        mpv.property("pause").as_bool(),
        Some(true),
        "mpv ist nicht in den Pausenzustand gewechselt"
    );

    mpv.send(&serde_json::json!(["set_property", "pause", false]))
        .expect("Wiedergabe sollte fortgesetzt werden können");
    std::thread::sleep(Duration::from_millis(500));
    assert_eq!(mpv.property("pause").as_bool(), Some(false));
}

