/// Stop must actually terminate the process, or playback leaks a process each time.
#[test]
fn stopping_terminates_the_process_and_removes_the_socket() {
    if !mpv_available() {
        return;
    }
    let Some(media) = test_media() else {
        return;
    };

    let mut mpv = Mpv::start(&media, &options()).expect("mpv sollte starten");
    let endpoint = mpv.ipc_endpoint().to_string();
    assert!(
        std::path::Path::new(&endpoint).exists(),
        "der IPC-Endpunkt wurde nicht angelegt: {endpoint}"
    );

    mpv.stop();
    // `stop` waits for the process, so the socket must be gone by now.
    assert!(
        !std::path::Path::new(&endpoint).exists(),
        "der IPC-Endpunkt blieb zurück: {endpoint}"
    );
}

/// The process must exit on its own when the last handle is dropped, without an
/// explicit `stop` — otherwise a panic or early return would leak it.
#[test]
fn dropping_the_handle_terminates_the_process() {
    if !mpv_available() {
        return;
    }
    let Some(media) = test_media() else {
        return;
    };

    let endpoint = {
        let mpv = Mpv::start(&media, &options()).expect("mpv sollte starten");
        mpv.ipc_endpoint().to_string()
    };
    // `Drop` calls `stop`, which waits for the child.
    assert!(
        !std::path::Path::new(&endpoint).exists(),
        "der IPC-Endpunkt blieb nach dem Drop zurück: {endpoint}"
    );
}

/// The HDR argument list must be accepted by the real mpv. The unit tests prove the
/// arguments are the intended ones; only a real invocation proves they exist in this
/// mpv build — and an unknown option makes mpv exit instead of playing.
#[test]
fn the_hdr_arguments_are_accepted_by_mpv() {
    if !mpv_available() {
        return;
    }
    let Some(media) = test_media() else {
        return;
    };

    for mode in [HdrMode::Auto, HdrMode::Passthrough, HdrMode::ToneMapSdr] {
        let options = PlayerOptions {
            hdr: mode,
            vo: "null".to_string(),
            fullscreen: false,
            ..Default::default()
        };
        let mut mpv =
            Mpv::start(&media, &options).unwrap_or_else(|e| panic!("mpv lehnte {mode:?} ab: {e}"));
        std::thread::sleep(Duration::from_secs(1));
        // A rejected option makes mpv exit immediately; a running process with a
        // positive duration means the whole argument list was accepted.
        assert!(!mpv.has_exited(), "mpv hat sich mit {mode:?} beendet");
        let duration = mpv.property("duration").as_f64().unwrap_or(0.0);
        assert!(duration > 0.0, "mpv spielte mit {mode:?} nichts ab");
    }
}

/// A per-profile `mpv.conf` in the config dir must be picked up. This is the plan's
/// requirement that the file is editable (task 1.3), and `--config-dir` replaces
/// mpv's default location rather than adding to it.
#[test]
fn a_profile_config_file_is_honoured() {
    if !mpv_available() {
        return;
    }
    let Some(media) = test_media() else {
        return;
    };

    let dir = std::env::temp_dir().join(format!("streamarr-mpv-conf-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    // A distinctive value that mpv would never choose on its own.
    std::fs::write(dir.join("mpv.conf"), "volume=37\n").unwrap();

    let options = PlayerOptions {
        config_dir: dir.clone(),
        vo: "null".to_string(),
        fullscreen: false,
        ..Default::default()
    };
    let mut mpv = Mpv::start(&media, &options).expect("mpv sollte starten");
    std::thread::sleep(Duration::from_secs(2));

    let volume = mpv.property("volume").as_f64().unwrap_or(0.0);
    assert!(
        (volume - 37.0).abs() < 0.5,
        "der Profil-mpv.conf wurde nicht gelesen (volume={volume}, erwartet 37)"
    );

    let _ = std::fs::remove_dir_all(&dir);
}
